-- Eumi 복지자원 관리 (복지자원 등록·조회·수정·삭제) / PostgreSQL 17
-- 2026-10-29 ERD 점검 결과
--   직접 설계: welfare_resource
--   뷰: v_resource_summary
--   V1(인증: member, organization)과 V2(사례자 관리: dim_region, v_sido, v_sigungu) 다음에 실행한다.
--
-- 규칙
--   * 모든 기관의 자원을 조회할 수 있고, 수정·삭제는 담당자(manager_member_id) 한 명만 한다 (API에서 확인).
--   * 삭제는 deleted_at에 시각만 기록한다. 조회는 모두 v_resource_summary(삭제 제외)로 한다.
--   * 실제 상태는 운영 종료일이 오늘보다 앞이면 '종료', 아니면 담당자가 고른 상태다 (뷰에서 계산).
--
-- 검색 조건 (목록·대시보드 복지자원 찾기·AI 추천이 같은 기준을 쓴다)
--   * 연령: :age = ANY(support_age_groups) OR '무관' = ANY(support_age_groups)
--   * 성별: support_gender IN (:gender, '무관')
--   * 행정동: dong_code = :dong OR (dong_code IS NULL AND sigungu_code = left(:dong, 5))
--   * 시군구: sigungu_code = :sigungu


-- 복지자원
CREATE TABLE welfare_resource (
    resource_id          BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    resource_name        VARCHAR(50)   NOT NULL,
    operating_org_name   VARCHAR(50)   NOT NULL,
    target               VARCHAR(100)  NOT NULL,
    support_age_groups   TEXT[]        NOT NULL,
    support_gender       VARCHAR(2)    NOT NULL,
    sigungu_code         VARCHAR(5)    NOT NULL,
    dong_code            VARCHAR(10),
    period_start         DATE          NOT NULL,
    period_end           DATE          NOT NULL,
    fee                  INT           NOT NULL,
    manual_status        VARCHAR(8)    NOT NULL,
    manager_member_id    BIGINT        NOT NULL,
    capacity             INT           NOT NULL,
    actual_participants  INT,
    support_content      VARCHAR(1000),
    apply_method         VARCHAR(200),
    created_at           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    deleted_at           TIMESTAMPTZ,
    CONSTRAINT pk_welfare_resource PRIMARY KEY (resource_id),
    CONSTRAINT fk_welfare_resource_dong FOREIGN KEY (dong_code) REFERENCES dim_region (adm_cd10),
    CONSTRAINT fk_welfare_resource_manager FOREIGN KEY (manager_member_id) REFERENCES member (member_id),
    -- 연령대 값만, 하나 이상, '무관'은 단독으로만
    CONSTRAINT ck_welfare_resource_age_groups CHECK (
        cardinality(support_age_groups) >= 1
        AND support_age_groups <@ ARRAY['청소년', '청년', '중장년', '노년', '무관']::TEXT[]
        AND (NOT ('무관' = ANY(support_age_groups)) OR cardinality(support_age_groups) = 1)
    ),
    CONSTRAINT ck_welfare_resource_gender CHECK (support_gender IN ('남', '여', '무관')),
    CONSTRAINT ck_welfare_resource_sigungu CHECK (sigungu_code ~ '^[0-9]{5}$'),
    -- 행정동이 있으면 그 행정동이 속한 시군구와 같아야 한다
    CONSTRAINT ck_welfare_resource_dong_in_sigungu CHECK (dong_code IS NULL OR left(dong_code, 5) = sigungu_code),
    CONSTRAINT ck_welfare_resource_period CHECK (period_end >= period_start),
    CONSTRAINT ck_welfare_resource_fee CHECK (fee >= 0),
    CONSTRAINT ck_welfare_resource_status CHECK (manual_status IN ('진행 중', '종료')),
    CONSTRAINT ck_welfare_resource_capacity CHECK (capacity >= 1),
    CONSTRAINT ck_welfare_resource_participants CHECK (actual_participants IS NULL OR actual_participants >= 0)
);

-- 마이페이지 담당 복지자원, 탈퇴 전 담당 자원 확인에 사용
CREATE INDEX ix_welfare_resource_manager ON welfare_resource (manager_member_id) WHERE deleted_at IS NULL;


-- 복지자원 목록·상세 조회용 (삭제 제외, 실제 상태·자동 종료·지역 이름·담당자 계산)
--   기본 정렬: status_order, period_end (진행 중 먼저, 운영 종료일 오름차순)
CREATE VIEW v_resource_summary AS
SELECT
    w.resource_id,
    w.resource_name,
    w.operating_org_name,
    w.target,
    w.support_age_groups,
    w.support_gender,
    left(w.sigungu_code, 2) AS sido_code,
    sd.sido_name,
    w.sigungu_code,
    sg.sigungu_name,
    w.dong_code,
    r.adm_nm AS dong_name,
    w.period_start,
    w.period_end,
    w.fee,
    w.manual_status,
    CASE WHEN w.period_end < current_date THEN '종료' ELSE w.manual_status END AS status,
    (w.manual_status = '진행 중' AND w.period_end < current_date) AS auto_ended,
    CASE WHEN w.period_end < current_date OR w.manual_status = '종료' THEN 1 ELSE 0 END AS status_order,
    w.manager_member_id,
    -- 담당자가 탈퇴했으면 '퇴사자'로 보여준다 (탈퇴 시 진행 중 자원은 인계되므로 종료된 자원만 해당)
    CASE WHEN m.withdrawn_at IS NULL THEN m.name ELSE '퇴사자' END AS manager_name,
    CASE WHEN m.withdrawn_at IS NULL THEN m.title END AS manager_title,
    (m.withdrawn_at IS NOT NULL) AS manager_withdrawn,
    o.org_name AS manager_org_name,
    w.capacity,
    w.actual_participants,
    w.support_content,
    w.apply_method,
    w.created_at,
    w.updated_at
FROM welfare_resource w
JOIN member m ON m.member_id = w.manager_member_id
JOIN organization o ON o.org_id = m.org_id
LEFT JOIN v_sigungu sg ON sg.sigungu_code = w.sigungu_code
LEFT JOIN v_sido sd ON sd.sido_code = left(w.sigungu_code, 2)
LEFT JOIN dim_region r ON r.adm_cd10 = w.dong_code
WHERE w.deleted_at IS NULL;


-- 논리명 · 규칙
