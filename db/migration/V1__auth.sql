-- Eumi 인증 영역 (로그인 · 회원가입 · 비밀번호 찾기) / PostgreSQL 17
-- 2026-10-29 ERD 점검 결과
--   직접 설계: organization, member, email_verification
--   Spring Session JDBC: SPRING_SESSION, SPRING_SESSION_ATTRIBUTES (로그인 세션, 구조 변경 금지)
--
-- 공통 규칙
--   * 로그인은 JWT 없이 서버 세션(Spring Session JDBC)으로 관리한다.
--   * 만료 시각은 행을 쓸 때 애플리케이션이 계산해 저장한다 (DB는 now()와 비교만 한다).
--   * 해시 키는 환경변수 하나로 관리한다 (키 교체용 컬럼 없음).
--   * BIGINT PK는 BY DEFAULT IDENTITY: 운영 단에서 ID를 지정해 적재할 수 있다.
--     ID를 지정해 넣었다면 적재 후 setval로 시퀀스를 맞춘다.
--     예) SELECT setval(pg_get_serial_sequence('organization', 'org_id'), (SELECT max(org_id) FROM organization));


-- 소속 기관 (운영 단에서 적재, 화면에서는 조회만)
CREATE TABLE organization (
    org_id                     BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    org_name                   VARCHAR(200) NOT NULL,
    jurisdiction_sigungu_code  VARCHAR(5)   NOT NULL,
    official_domain            VARCHAR(253) NOT NULL,
    created_at                 TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at                 TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_organization PRIMARY KEY (org_id),
    CONSTRAINT ck_organization_domain_lower CHECK (official_domain = lower(btrim(official_domain)))
);


-- 회원
CREATE TABLE member (
    member_id                 BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    org_id                    BIGINT       NOT NULL,
    email_normalized          VARCHAR(254) NOT NULL,
    name                      VARCHAR(100) NOT NULL,
    title                     VARCHAR(100),
    phone                     VARCHAR(13),
    password_hash             TEXT         NOT NULL,
    temp_password_expires_at  TIMESTAMPTZ,
    created_at                TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at                TIMESTAMPTZ  NOT NULL DEFAULT now(),
    withdrawn_at              TIMESTAMPTZ,
    CONSTRAINT pk_member PRIMARY KEY (member_id),
    CONSTRAINT fk_member_org FOREIGN KEY (org_id) REFERENCES organization (org_id),
    CONSTRAINT ck_member_email_normalized CHECK (email_normalized = lower(btrim(email_normalized)))
);

-- 탈퇴한 회원을 포함해 이메일 중복 금지 → 탈퇴한 이메일로는 재가입 불가
CREATE UNIQUE INDEX uq_member_email ON member (email_normalized);
CREATE INDEX ix_member_org_id ON member (org_id);


-- 가입 이메일 인증 (이메일당 한 행: 재요청 시 기존 행 삭제 후 새로 생성, 가입 완료 시 삭제)
CREATE TABLE email_verification (
    verification_id       UUID         NOT NULL DEFAULT gen_random_uuid(),
    org_id                BIGINT       NOT NULL,
    email_normalized      VARCHAR(254) NOT NULL,
    code_hash             BYTEA        NOT NULL,
    expires_at            TIMESTAMPTZ  NOT NULL,
    failed_attempt_count  SMALLINT     NOT NULL DEFAULT 0,
    verified_at           TIMESTAMPTZ,
    proof_hash            BYTEA,
    proof_expires_at      TIMESTAMPTZ,
    created_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_email_verification PRIMARY KEY (verification_id),
    CONSTRAINT fk_email_verification_org FOREIGN KEY (org_id) REFERENCES organization (org_id),
    CONSTRAINT uq_email_verification_email UNIQUE (email_normalized),
    CONSTRAINT ck_email_verification_email_normalized CHECK (email_normalized = lower(btrim(email_normalized))),
    CONSTRAINT ck_email_verification_attempts CHECK (failed_attempt_count >= 0),
    -- 인증 전에는 가입 확인 토큰이 없고, 인증 후에는 세 값이 함께 채워진다
    CONSTRAINT ck_email_verification_proof CHECK (
        (verified_at IS NULL AND proof_hash IS NULL AND proof_expires_at IS NULL)
        OR (verified_at IS NOT NULL AND proof_hash IS NOT NULL AND proof_expires_at IS NOT NULL)
    )
);


-- 로그인 세션: Spring Session JDBC 공식 스키마 (spring-session-jdbc의 schema-postgresql.sql 그대로)
--   * Spring Session이 이 이름·컬럼으로 직접 조회하므로 구조를 바꾸지 않는다.
--   * Flyway가 만들므로 설정은 spring.session.jdbc.initialize-schema=never
--   * PRINCIPAL_NAME에는 member_id를 문자열로 넣는다 (회원별 세션 조회·삭제에 사용, FK 없음)
CREATE TABLE SPRING_SESSION (
	PRIMARY_ID CHAR(36) NOT NULL,
	SESSION_ID CHAR(36) NOT NULL,
	CREATION_TIME BIGINT NOT NULL,
	LAST_ACCESS_TIME BIGINT NOT NULL,
	MAX_INACTIVE_INTERVAL INT NOT NULL,
	EXPIRY_TIME BIGINT NOT NULL,
	PRINCIPAL_NAME VARCHAR(100),
	CONSTRAINT SPRING_SESSION_PK PRIMARY KEY (PRIMARY_ID)
);

CREATE UNIQUE INDEX SPRING_SESSION_IX1 ON SPRING_SESSION (SESSION_ID);
CREATE INDEX SPRING_SESSION_IX2 ON SPRING_SESSION (EXPIRY_TIME);
CREATE INDEX SPRING_SESSION_IX3 ON SPRING_SESSION (PRINCIPAL_NAME);

CREATE TABLE SPRING_SESSION_ATTRIBUTES (
	SESSION_PRIMARY_ID CHAR(36) NOT NULL,
	ATTRIBUTE_NAME VARCHAR(200) NOT NULL,
	ATTRIBUTE_BYTES BYTEA NOT NULL,
	CONSTRAINT SPRING_SESSION_ATTRIBUTES_PK PRIMARY KEY (SESSION_PRIMARY_ID, ATTRIBUTE_NAME),
	CONSTRAINT SPRING_SESSION_ATTRIBUTES_FK FOREIGN KEY (SESSION_PRIMARY_ID) REFERENCES SPRING_SESSION(PRIMARY_ID) ON DELETE CASCADE
);


