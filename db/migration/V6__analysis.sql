-- Eumi 위험 탐지 대시보드 — analysis 스키마 (데이터 분석 파이프라인 · AI 근거) / PostgreSQL 17
-- 2026-10-30 ERD 점검 결과
--   데이터 분석 정의(첨부 ERD 그대로): dim_grid100, re_apt_trade, bg_region_indicator, bg_region_detail,
--     bh_region_indicator, bh_grid_indicator, bh_grid_anomaly, flow_detail, bg_grid_indicator
--   추가: bh_region_contribution (점수 계산식을 가진 분석 모듈이 지표별 기여도를 저장)
--   V5(region_result) 다음에 실행한다. 이 파일과 이후 analysis 마이그레이션은 데이터 분석 파트가 관리한다.
--
-- 이 파일에서 정한 것 (컬럼은 첨부 ERD 그대로, 아래는 제약·인덱스만)
--   * NOT NULL: PK, FK, 격자 좌표, re_apt_trade.contract_date(재적재 기준), updated_at. 측정값은 결측·비공개 값 대비 NULL 허용.
--   * updated_at: TIMESTAMP(한국 시간), 값을 안 주면 적재 시각.
--   * 월 단위 테이블의 period_start는 그 달 1일만 허용.
--   * 조회 순서에 맞춘 PK 컬럼 순서: bg_region_detail (기준월, 행정동, 항목), flow_detail (기준월, 격자, 구분, 구분 값).
--
-- 적재 규칙 (파이프라인)
--   * DROP·전체 TRUNCATE 금지 (Spark overwrite 기본 동작 포함). 그 달(bg_grid_indicator는 그 연도) 행을 지운 뒤 append, 또는 UPSERT.
--     dim_grid100은 다른 테이블이 참조하므로 UPSERT로만 갱신한다.
--   * re_apt_trade: 원본에 거래 ID가 없으므로 같은 계약월을 지운 뒤 다시 넣는다 (trade_id는 DB가 발급).
--   * 적재 순서: dim_grid100 → 지표·상세 → (public.region_result) → bh_grid_anomaly, bh_region_contribution
--
-- 코드표 (문서로 관리, AI 코드에 반영)
--   * 지표 컬럼(h12_… 등)·bg_region_detail.item_cd·flow_detail.dim_value의 한글 이름과 단위
--   * bh_region_contribution.indicator_cd = bh_region_indicator의 컬럼 이름
--   * dim_grid100.gx·gy의 좌표계, 경계에 걸친 격자를 어느 동에 넣는지 기준

CREATE SCHEMA IF NOT EXISTS analysis;


-- 100m 격자 기준
CREATE TABLE analysis.dim_grid100 (
    grid_cd     VARCHAR(10)  NOT NULL,
    gx          INT          NOT NULL,
    gy          INT          NOT NULL,
    updated_at  TIMESTAMP    NOT NULL DEFAULT now(),
    adm_cd10    VARCHAR(10)  NOT NULL,
    CONSTRAINT pk_dim_grid100 PRIMARY KEY (grid_cd),
    CONSTRAINT fk_dim_grid100_region FOREIGN KEY (adm_cd10) REFERENCES public.dim_region (adm_cd10)
);

-- 동 단위 격자 조회 (AI 근거, Tableau 내보내기)
CREATE INDEX ix_dim_grid100_region ON analysis.dim_grid100 (adm_cd10);


-- 아파트 실거래가
CREATE TABLE analysis.re_apt_trade (
    trade_id           BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    deal_type          VARCHAR(10),
    contract_date      DATE          NOT NULL,
    apt_name           VARCHAR(100),
    exclusive_area_m2  DECIMAL(7,2),
    floor              SMALLINT,
    build_year         SMALLINT,
    price_10k          INT,
    monthly_rent_10k   INT,
    lat                DECIMAL(10,7),
    lon                DECIMAL(10,7),
    updated_at         TIMESTAMP     NOT NULL DEFAULT now(),
    adm_cd10           VARCHAR(10)   NOT NULL,
    CONSTRAINT pk_re_apt_trade PRIMARY KEY (trade_id),
    CONSTRAINT fk_re_apt_trade_region FOREIGN KEY (adm_cd10) REFERENCES public.dim_region (adm_cd10)
);

-- 동·기간 조회 (AI 근거), 계약월 단위 재적재
CREATE INDEX ix_re_apt_trade_region ON analysis.re_apt_trade (adm_cd10, contract_date);


-- 읍면동 배경 지표
CREATE TABLE analysis.bg_region_indicator (
    period_start       DATE          NOT NULL,
    adm_cd10           VARCHAR(10)   NOT NULL,
    male_pct           DECIMAL(5,2),
    one_person_hh_pct  DECIMAL(5,2),
    non_apt_pct        DECIMAL(5,2),
    age65_pct          DECIMAL(5,2),
    park_area_pct      DECIMAL(5,2),
    bus_stop_density   DECIMAL(7,2),
    updated_at         TIMESTAMP     NOT NULL DEFAULT now(),
    CONSTRAINT pk_bg_region_indicator PRIMARY KEY (period_start, adm_cd10),
    CONSTRAINT fk_bg_region_indicator_region FOREIGN KEY (adm_cd10) REFERENCES public.dim_region (adm_cd10),
    CONSTRAINT ck_bg_region_indicator_month CHECK (period_start = date_trunc('month', period_start)::date)
);


-- 배경 상세 (원값: 지표의 분자·분모 등, 비율은 bg_region_indicator에만)
CREATE TABLE analysis.bg_region_detail (
    period_start  DATE           NOT NULL,
    item_cd       VARCHAR(30)    NOT NULL,
    adm_cd10      VARCHAR(10)    NOT NULL,
    value         DECIMAL(14,2),
    updated_at    TIMESTAMP      NOT NULL DEFAULT now(),
    CONSTRAINT pk_bg_region_detail PRIMARY KEY (period_start, adm_cd10, item_cd),
    CONSTRAINT fk_bg_region_detail_region FOREIGN KEY (adm_cd10) REFERENCES public.dim_region (adm_cd10),
    CONSTRAINT ck_bg_region_detail_month CHECK (period_start = date_trunc('month', period_start)::date)
);


-- 읍면동 행동 지표
CREATE TABLE analysis.bh_region_indicator (
    period_start                    DATE           NOT NULL,
    adm_cd10                        VARCHAR(10)    NOT NULL,
    activity_daily                  DECIMAL(14,2),
    h12_evening_day_ratio           DECIMAL(10,6),
    h13_commute_ratio               DECIMAL(10,6),
    h14_hour_entropy                DECIMAL(10,6),
    h15_weekday_entropy             DECIMAL(10,6),
    h18_senior_male_share           DECIMAL(10,6),
    h19_age_entropy                 DECIMAL(10,6),
    h20_senior_representation       DECIMAL(10,6),
    h21_male50plus_representation   DECIMAL(10,6),
    h26_weekend_weekday_change_gap  DECIMAL(10,6),
    h29_senior_gender_change_gap    DECIMAL(10,6),
    h30_hour_profile_distance       DECIMAL(10,6),
    h31_weekday_profile_distance    DECIMAL(10,6),
    updated_at                      TIMESTAMP      NOT NULL DEFAULT now(),
    CONSTRAINT pk_bh_region_indicator PRIMARY KEY (period_start, adm_cd10),
    CONSTRAINT fk_bh_region_indicator_region FOREIGN KEY (adm_cd10) REFERENCES public.dim_region (adm_cd10),
    CONSTRAINT ck_bh_region_indicator_month CHECK (period_start = date_trunc('month', period_start)::date)
);


-- 읍면동 행동 점수 지표별 기여도 (추가: 분석 모듈이 점수와 함께 계산)
--   contribution = 그 달 행동 이상 점수에 대한 지표의 기여 (점수 단위)
--   전월 대비 점수 변화 요인 = 이번 달 기여도 - 전월 기여도 (요인 합 = 점수 변화)
CREATE TABLE analysis.bh_region_contribution (
    period_start  DATE           NOT NULL,
    adm_cd10      VARCHAR(10)    NOT NULL,
    indicator_cd  VARCHAR(50)    NOT NULL,
    contribution  DECIMAL(10,6)  NOT NULL,
    updated_at    TIMESTAMP      NOT NULL DEFAULT now(),
    CONSTRAINT pk_bh_region_contribution PRIMARY KEY (period_start, adm_cd10, indicator_cd),
    CONSTRAINT fk_bh_region_contribution_result FOREIGN KEY (period_start, adm_cd10)
        REFERENCES public.region_result (period_start, adm_cd10) ON DELETE CASCADE
);


-- 격자 행동 지표
CREATE TABLE analysis.bh_grid_indicator (
    period_start                    DATE           NOT NULL,
    grid_cd                         VARCHAR(10)    NOT NULL,
    activity_daily                  DECIMAL(12,2),
    h12_evening_day_ratio           DECIMAL(10,6),
    h13_commute_ratio               DECIMAL(10,6),
    h14_hour_entropy                DECIMAL(10,6),
    h15_weekday_entropy             DECIMAL(10,6),
    h18_senior_male_share           DECIMAL(10,6),
    h19_age_entropy                 DECIMAL(10,6),
    h26_weekend_weekday_change_gap  DECIMAL(10,6),
    h29_senior_gender_change_gap    DECIMAL(10,6),
    h30_hour_profile_distance       DECIMAL(10,6),
    h31_weekday_profile_distance    DECIMAL(10,6),
    updated_at                      TIMESTAMP      NOT NULL DEFAULT now(),
    CONSTRAINT pk_bh_grid_indicator PRIMARY KEY (period_start, grid_cd),
    CONSTRAINT fk_bh_grid_indicator_grid FOREIGN KEY (grid_cd) REFERENCES analysis.dim_grid100 (grid_cd),
    CONSTRAINT ck_bh_grid_indicator_month CHECK (period_start = date_trunc('month', period_start)::date)
);


-- 격자 행동 이상 점수 (읍면동 격자 지도의 색)
CREATE TABLE analysis.bh_grid_anomaly (
    period_start   DATE          NOT NULL,
    grid_cd        VARCHAR(10)   NOT NULL,
    anomaly_score  DECIMAL(7,2),
    updated_at     TIMESTAMP     NOT NULL DEFAULT now(),
    CONSTRAINT pk_bh_grid_anomaly PRIMARY KEY (period_start, grid_cd),
    CONSTRAINT fk_bh_grid_anomaly_grid FOREIGN KEY (grid_cd) REFERENCES analysis.dim_grid100 (grid_cd),
    CONSTRAINT ck_bh_grid_anomaly_month CHECK (period_start = date_trunc('month', period_start)::date)
);


-- 유동 상세 (격자 · 구분별 월 합계)
CREATE TABLE analysis.flow_detail (
    period_start  DATE           NOT NULL,
    dim_type      VARCHAR(10)    NOT NULL,
    dim_value     VARCHAR(10)    NOT NULL,
    grid_cd       VARCHAR(10)    NOT NULL,
    flow_sum      DECIMAL(16,4),
    day_count     SMALLINT,
    updated_at    TIMESTAMP      NOT NULL DEFAULT now(),
    CONSTRAINT pk_flow_detail PRIMARY KEY (period_start, grid_cd, dim_type, dim_value),
    CONSTRAINT fk_flow_detail_grid FOREIGN KEY (grid_cd) REFERENCES analysis.dim_grid100 (grid_cd),
    CONSTRAINT ck_flow_detail_month CHECK (period_start = date_trunc('month', period_start)::date),
    CONSTRAINT ck_flow_detail_dim_type CHECK (dim_type IN ('hour', 'weekday', 'sex_age'))
);


-- 격자 배경 지표 (연 단위)
CREATE TABLE analysis.bg_grid_indicator (
    ref_year     SMALLINT     NOT NULL,
    grid_cd      VARCHAR(10)  NOT NULL,
    pop_total    INT,
    pop_male     INT,
    pop_female   INT,
    households   INT,
    housing      INT,
    businesses   INT,
    employees    INT,
    updated_at   TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT pk_bg_grid_indicator PRIMARY KEY (ref_year, grid_cd),
    CONSTRAINT fk_bg_grid_indicator_grid FOREIGN KEY (grid_cd) REFERENCES analysis.dim_grid100 (grid_cd)
);


