-- Eumi AI Agent 패널 (AI 대화, 마이페이지 AI 대화 기록) / PostgreSQL 17
-- 2026-10-29 ERD 점검 결과
--   직접 설계: ai_conversation, ai_conversation_turn
--   뷰: v_conversation_summary
--   V1(인증: member) 다음에 실행한다.
--
-- 규칙
--   * 완료된 답변만 저장한다. 실패·시간 초과된 질문은 남기지 않는다.
--   * 답변 중인 실행(runId)과 그 소유자, AI 질문 요청 제한은 Spring 메모리에서 관리한다 (서버 한 대 전제).
--   * conversation_id는 Spring이 질문을 받을 때 UUID로 만들어 FastAPI·SSE에 넘긴다 (저장 전이라 DB가 발급할 수 없음).
--   * 질문은 개인정보(이름 등)를 가린 값으로 저장한다. 대화에는 사례자 ID를 저장하지 않는다.
--   * 보관 기간: 마지막 대화일부터 3개월. 매일 한 번 삭제 작업이 delete_scheduled_at이 지난 대화를 지운다.


-- AI 대화
CREATE TABLE ai_conversation (
    conversation_id      UUID        NOT NULL,
    member_id            BIGINT      NOT NULL,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_message_at      TIMESTAMPTZ NOT NULL,
    delete_scheduled_at  DATE        NOT NULL,
    CONSTRAINT pk_ai_conversation PRIMARY KEY (conversation_id),
    CONSTRAINT fk_ai_conversation_member FOREIGN KEY (member_id) REFERENCES member (member_id)
);

-- 내 대화 목록(마지막 대화 최신순), 탈퇴 시 전부 삭제에 사용
CREATE INDEX ix_ai_conversation_member ON ai_conversation (member_id, last_message_at DESC);


-- AI 대화 질문·답변 (완료된 답변만)
--   progress_steps: SSE step 이벤트의 단계별 마지막 상태 목록 [{stepId, stepName, status, detail}, ...]
--   answer_blocks : SSE answer 이벤트의 블록 목록 [{kind: text | list | resourceCards, ...}, ...]
--                   resourceCards는 resource_id와 자원 정보 스냅샷을 함께 담는다
CREATE TABLE ai_conversation_turn (
    turn_id          BIGINT      GENERATED BY DEFAULT AS IDENTITY,
    conversation_id  UUID        NOT NULL,
    question         TEXT        NOT NULL,
    progress_steps   JSONB       NOT NULL,
    answer_blocks    JSONB       NOT NULL,
    asked_at         TIMESTAMPTZ NOT NULL,
    completed_at     TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_ai_conversation_turn PRIMARY KEY (turn_id),
    CONSTRAINT fk_ai_conversation_turn_conversation FOREIGN KEY (conversation_id) REFERENCES ai_conversation (conversation_id) ON DELETE CASCADE,
    CONSTRAINT ck_ai_conversation_turn_time CHECK (completed_at >= asked_at),
    CONSTRAINT ck_ai_conversation_turn_steps CHECK (jsonb_typeof(progress_steps) = 'array'),
    CONSTRAINT ck_ai_conversation_turn_blocks CHECK (jsonb_typeof(answer_blocks) = 'array')
);

-- 대화 내용 조회(질문 순서대로)에 사용
CREATE INDEX ix_ai_conversation_turn_conversation ON ai_conversation_turn (conversation_id, asked_at);


-- 마이페이지 AI 대화 기록 목록용 (첫 질문을 제목으로, 질문 수, 보관 기간이 지난 대화 제외)
CREATE VIEW v_conversation_summary AS
SELECT
    c.conversation_id,
    c.member_id,
    (SELECT t.question FROM ai_conversation_turn t
      WHERE t.conversation_id = c.conversation_id
      ORDER BY t.asked_at, t.turn_id LIMIT 1) AS first_question,
    (SELECT count(*) FROM ai_conversation_turn t
      WHERE t.conversation_id = c.conversation_id) AS question_count,
    c.created_at,
    c.last_message_at,
    c.delete_scheduled_at
FROM ai_conversation c
WHERE c.delete_scheduled_at > current_date;


-- 논리명 · 규칙
COMMENT ON TABLE  ai_conversation IS 'AI 대화';
COMMENT ON COLUMN ai_conversation.conversation_id IS 'AI 대화 ID (Spring이 만드는 UUID)';
COMMENT ON COLUMN ai_conversation.member_id IS '대화 소유 회원 ID';
COMMENT ON COLUMN ai_conversation.created_at IS 'AI 대화 생성 일시';
COMMENT ON COLUMN ai_conversation.last_message_at IS '마지막 AI 답변 완료 일시 (목록 정렬, 보관 기간 기준)';
COMMENT ON COLUMN ai_conversation.delete_scheduled_at IS 'AI 대화 삭제 예정일 (마지막 대화일 + 3개월, 답변이 끝날 때마다 갱신)';

COMMENT ON TABLE  ai_conversation_turn IS 'AI 대화 질문·답변';
COMMENT ON COLUMN ai_conversation_turn.turn_id IS '질문·답변 ID';
COMMENT ON COLUMN ai_conversation_turn.conversation_id IS '연결된 AI 대화 ID';
COMMENT ON COLUMN ai_conversation_turn.question IS '개인정보를 가린 사용자 질문';
COMMENT ON COLUMN ai_conversation_turn.progress_steps IS '에이전트 진행 단계 (단계별 마지막 상태 목록)';
COMMENT ON COLUMN ai_conversation_turn.answer_blocks IS 'AI 답변 블록 목록 (추천 카드는 자원 정보 스냅샷 포함)';
COMMENT ON COLUMN ai_conversation_turn.asked_at IS '사용자 질문 일시';
COMMENT ON COLUMN ai_conversation_turn.completed_at IS 'AI 답변 완료·저장 일시';
