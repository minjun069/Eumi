-- 스트리밍 진행 기록: 유동 상세 스트리밍(m2_process/stream_flow_detail.py)이 마이크로배치마다 한 행을 남긴다 / PostgreSQL 17
-- 2026-11-10 파이프라인 모니터링(Grafana) 작업 ('Eumi ERD 변경 기록' > 데이터 파이프라인 > 11/10 스트리밍 진행 기록)
--   * 지금까지 스트리밍이 살아 있는지 · 밀리는지는 그 터미널의 로그로만 볼 수 있었다.
--     Grafana "Eumi 스트리밍" 대시보드가 이 표를 5초마다 읽는다 (Prometheus 없이 PostgreSQL 만 읽는 구조 그대로).
--   * Spark 가 배치를 끝낼 때마다 주는 진행 정보에서 뽑는다. 메시지가 없어도 약 10초마다 한 행이 들어와 "살아 있음"을 알 수 있다.
--     스트림을 강제 종료하면 끝났다는 행은 남지 않으므로, 멈춤은 "마지막 행이 30초보다 오래됨"으로 판단한다.
--   * run_id: Spark 가 스트림을 시작할 때마다 새로 주는 값 (재시작 구분). batch_id: 그 안의 배치 번호. 쉬는 동안에는 같은 번호가 반복된다.
--   * lag_rows: 기록하는 시점의 Kafka 최신 위치 − Spark 가 읽은 위치 (파티션 합). Spark 는 읽은 위치를 Kafka 가 아니라 체크포인트에 두므로 여기서만 알 수 있다.
--   * event_time_max: 그 배치에서 본 가장 늦은 데이터 시각. watermark: 이 시각보다 이른 데이터는 마감 (event_time_max − 1시간을 따라간다).
--   * closed_days · loaded_rows: 그 배치에서 하루 윈도가 닫혀 flow_detail 에 더한 날짜와 행 수 (닫힌 날이 없으면 NULL).
--     더하는 데 1분 가까이 걸려서, 시작할 때 closed_days 만 있고 loaded_rows 가 NULL 인 "적재 중" 표시 행을 먼저 하나 남긴다.
--   * 스트림을 시작할 때 7일 지난 행을 지운다. 화면 · AI는 쓰지 않는다. 권한은 afterMigrate의 analysis 전체 규칙을 그대로 따른다.
CREATE TABLE analysis.stream_progress (
    progress_id     BIGINT         GENERATED BY DEFAULT AS IDENTITY,
    recorded_at     TIMESTAMPTZ    NOT NULL DEFAULT now(),
    run_id          VARCHAR(36)    NOT NULL,
    batch_id        BIGINT         NOT NULL,
    input_rows      BIGINT         NOT NULL,
    input_rps       NUMERIC(12,1),
    processed_rps   NUMERIC(12,1),
    lag_rows        BIGINT,
    event_time_max  TIMESTAMPTZ,
    watermark       TIMESTAMPTZ,
    duration_ms     INTEGER,
    state_rows      BIGINT,
    closed_days     DATE[],
    loaded_rows     INTEGER,
    CONSTRAINT pk_stream_progress PRIMARY KEY (progress_id)
);
CREATE INDEX ix_stream_progress_recorded_at ON analysis.stream_progress (recorded_at);
