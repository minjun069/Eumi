-- AI 대화 메시지 (A 방식) / PostgreSQL 17
-- 2026-11-02 AI 회의 결정: "AI 에이전트 패널 동작 흐름 (A 방식)"
--   BE가 질문 행을 저장하고, AI가 진행·완료·실패·취소 행을 DB에 직접 저장하고, 화면은 1초마다 새 행을 조회한다.
--   ai_conversation_turn(질문과 답변을 한 행에 묶음) → ai_message(행 하나 = 질문 / 진행 단계 / 끝 행)
--   ai_conversation은 컬럼 그대로. 실행 ID = 대화 ID. 실행 종료 일시·삭제 예정일은 끝 행이 들어올 때 트리거가 갱신한다.
--   v_conversation_summary는 ai_message 기준으로 바꾼다 (출력 컬럼 이름·타입 그대로).
--
-- 규칙
--   * 질문 행은 BE(eumi_app)가, AI 행은 AI(eumi_ai)가 쓴다. AI가 응답하지 않을 때의 실패·취소 행만 BE가 대신 쓴다.
--   * AI는 행을 하나 쓸 때마다 바로 커밋한다 (커밋해야 화면 조회에 보인다).
--   * 한 질문에 끝 행(완료·실패·취소)은 하나만 들어간다. 이미 끝난 질문에 늦게 쓰는 행은 DB가 거부한다 (SQLSTATE 23505).
--   * 실패 원인은 저장하지 않는다. 질문은 개인정보를 가린 값으로 저장한다.
--   * ai_conversation_turn에 행이 있으면 멈춘다. 한 행에 묶인 질문·답변은 새 구조로 그대로 옮길 수 없어서 옮길 방법을 먼저 정해야 한다.

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM ai_conversation_turn) THEN
        RAISE EXCEPTION 'ai_conversation_turn에 행이 있어 ai_message로 바꿀 수 없습니다. 옮길 방법을 정한 뒤 다시 실행하세요.';
    END IF;
END $$;


-- 대화 행은 첫 질문을 저장할 때 만든다. 끝 행이 들어오기 전까지는 만든 시각을 기준으로 둔다
ALTER TABLE ai_conversation
    ALTER COLUMN last_message_at     SET DEFAULT now(),
    ALTER COLUMN delete_scheduled_at SET DEFAULT ((now() AT TIME ZONE 'Asia/Seoul')::date + INTERVAL '3 months')::date;


-- AI 대화 메시지
--   role   : Member(사용자) / AI
--   status : 질문(Member) / 진행·완료·실패·취소(AI)
--   content: 질문 행은 질문, 진행 행은 단계 이름(label), 완료 행은 최종 답변. 실패·취소 행은 비어 있어도 된다
--   details: 단계의 상세 설명. 질문 행에서는 쓰지 않는다
CREATE TABLE ai_message (
    message_id       BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    conversation_id  UUID         NOT NULL,
    question_id      BIGINT,
    role             VARCHAR(10)  NOT NULL,
    status           VARCHAR(10)  NOT NULL,
    content          TEXT,
    details          TEXT,
    artifacts        JSONB,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_ai_message PRIMARY KEY (message_id),
    CONSTRAINT uq_ai_message_conversation_message UNIQUE (conversation_id, message_id),
    CONSTRAINT fk_ai_message_conversation FOREIGN KEY (conversation_id) REFERENCES ai_conversation (conversation_id) ON DELETE CASCADE,
    CONSTRAINT fk_ai_message_question FOREIGN KEY (conversation_id, question_id) REFERENCES ai_message (conversation_id, message_id) ON DELETE CASCADE,
    CONSTRAINT ck_ai_message_role CHECK (role IN ('Member', 'AI')),
    CONSTRAINT ck_ai_message_status CHECK (status IN ('질문', '진행', '완료', '실패', '취소')),
    CONSTRAINT ck_ai_message_role_status CHECK (
        (role = 'Member' AND status = '질문' AND question_id IS NULL)
        OR (role = 'AI' AND status <> '질문' AND question_id IS NOT NULL)
    ),
    CONSTRAINT ck_ai_message_content CHECK (status IN ('실패', '취소') OR content IS NOT NULL),
    CONSTRAINT ck_ai_message_details CHECK (status <> '질문' OR details IS NULL)
);

-- 한 질문에 끝 행은 하나 (완료·실패·취소 중 먼저 저장된 것만 남는다)
CREATE UNIQUE INDEX uq_ai_message_question_end ON ai_message (question_id) WHERE status IN ('완료', '실패', '취소');

-- 질문별 AI 행 조회, 질문 행 삭제 시 FK 확인에 사용
CREATE INDEX ix_ai_message_question ON ai_message (question_id);


-- 끝 행 처리
--   1) 이미 끝난 질문에 AI 행이 더 들어오면 거부한다 (끝 행끼리는 uq_ai_message_question_end가 막는다)
--   2) 끝 행이 들어오면 대화의 실행 종료 일시와 삭제 예정일(서울 날짜 + 3개월, 말일 보정)을 갱신한다
--   AI 계정은 ai_conversation을 수정할 권한이 없으므로 함수 소유자 권한으로 실행한다
CREATE FUNCTION ai_message_after_insert() RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
    IF NEW.role = 'AI' AND EXISTS (
        SELECT 1 FROM ai_message m
         WHERE m.question_id = NEW.question_id
           AND m.message_id <> NEW.message_id
           AND m.status IN ('완료', '실패', '취소')
    ) THEN
        RAISE EXCEPTION '이미 끝난 질문입니다 (question_id=%)', NEW.question_id
            USING ERRCODE = 'unique_violation';
    END IF;

    IF NEW.status IN ('완료', '실패', '취소') THEN
        UPDATE ai_conversation
           SET last_message_at     = NEW.created_at,
               delete_scheduled_at = ((NEW.created_at AT TIME ZONE 'Asia/Seoul')::date + INTERVAL '3 months')::date
         WHERE conversation_id = NEW.conversation_id;
    END IF;

    RETURN NULL;
END
$$;

CREATE TRIGGER trg_ai_message_after_insert
    AFTER INSERT ON ai_message
    FOR EACH ROW EXECUTE FUNCTION ai_message_after_insert();


-- 마이페이지 AI 대화 기록 목록용 (첫 질문을 제목으로, 질문 수, 보관 기간이 지난 대화 제외)
--   질문 수는 실패·취소된 질문도 센다
CREATE OR REPLACE VIEW v_conversation_summary AS
SELECT
    c.conversation_id,
    c.member_id,
    (SELECT m.content FROM ai_message m
      WHERE m.conversation_id = c.conversation_id AND m.status = '질문'
      ORDER BY m.message_id LIMIT 1) AS first_question,
    (SELECT count(*) FROM ai_message m
      WHERE m.conversation_id = c.conversation_id AND m.status = '질문') AS question_count,
    c.created_at,
    c.last_message_at,
    c.delete_scheduled_at
FROM ai_conversation c
WHERE c.delete_scheduled_at > current_date;


DROP TABLE ai_conversation_turn;


