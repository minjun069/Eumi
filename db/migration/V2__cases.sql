-- Eumi 사례자 관리 (사례자 등록·조회·수정·삭제, 상담 기록 등록·조회·수정·삭제) / PostgreSQL 17
-- 2026-10-29 ERD 점검 결과
--   데이터 분석 관리: dim_region (정의는 Flyway, 데이터는 파이프라인이 UPSERT로 갱신)
--   직접 설계: case_record, case_manager, consultation
--   뷰·함수: v_sido, v_sigungu, v_case_summary, next_management_no
--   인증 영역 migration(organization, member)이 먼저 실행되어야 한다.
--
-- 규칙
--   * 사례자와 상담 기록은 그 사례자의 담당자만 조회·수정·삭제한다 (API에서 확인).
--   * 사례자를 지우면 상담 기록과 담당자 연결도 함께 지워진다.
--   * 나이(만)·연령대·최근 기록일은 저장하지 않고 v_case_summary에서 계산한다.


-- 행정동 기준 (데이터 분석 파트 테이블)
--   * case_record가 FK로 참조하므로 DROP·TRUNCATE·pandas to_sql(replace)로 바꾸지 않는다. UPSERT로만 갱신한다.
--   * adm_cd10은 행정안전부 행정동 코드 10자리: 앞 2자리 = 시도 코드, 앞 5자리 = 시군구 코드
--   * 시도 이름은 이 테이블에 없으므로 v_sido에서 시도 코드로 붙인다.
CREATE TABLE dim_region (
    adm_cd10    VARCHAR(10) NOT NULL,
    adm_cd8     VARCHAR(8),
    adm_nm      VARCHAR(30) NOT NULL,
    sgg_nm      VARCHAR(20) NOT NULL,
    geom        TEXT,
    updated_at  TIMESTAMP,
    CONSTRAINT pk_dim_region PRIMARY KEY (adm_cd10)
);


-- 사례자
CREATE TABLE case_record (
    case_id              BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    org_id               BIGINT       NOT NULL,
    management_no        VARCHAR(9)   NOT NULL,
    name                 VARCHAR(100) NOT NULL,
    birth_date           DATE         NOT NULL,
    gender               VARCHAR(1)   NOT NULL,
    dong_code            VARCHAR(10)  NOT NULL,
    first_registered_at  DATE         NOT NULL,
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_case_record PRIMARY KEY (case_id),
    CONSTRAINT fk_case_record_org FOREIGN KEY (org_id) REFERENCES organization (org_id),
    CONSTRAINT fk_case_record_dong FOREIGN KEY (dong_code) REFERENCES dim_region (adm_cd10),
    CONSTRAINT uq_case_record_management_no UNIQUE (org_id, management_no),
    CONSTRAINT ck_case_record_management_no CHECK (management_no ~ '^[0-9]{4}-[0-9]{4}$'),
    CONSTRAINT ck_case_record_gender CHECK (gender IN ('남', '여'))
);


-- 사례자 담당자 (공동 담당 가능, 담당자만 사례자를 볼 수 있음, 연결 테이블이라 생성·수정 일시 없음)
CREATE TABLE case_manager (
    case_id      BIGINT      NOT NULL,
    member_id    BIGINT      NOT NULL,
    CONSTRAINT pk_case_manager PRIMARY KEY (case_id, member_id),
    CONSTRAINT fk_case_manager_case FOREIGN KEY (case_id) REFERENCES case_record (case_id) ON DELETE CASCADE,
    CONSTRAINT fk_case_manager_member FOREIGN KEY (member_id) REFERENCES member (member_id)
);

-- 로그인한 회원이 담당하는 사례자 목록, 탈퇴 전 혼자 담당 중인 사례자 확인에 사용
CREATE INDEX ix_case_manager_member_id ON case_manager (member_id);


-- 상담 기록
CREATE TABLE consultation (
    consultation_id     BIGINT         GENERATED BY DEFAULT AS IDENTITY,
    case_id             BIGINT         NOT NULL,
    consulted_at        DATE           NOT NULL,
    purpose             VARCHAR(200)   NOT NULL,
    category            VARCHAR(8)     NOT NULL,
    category_etc        VARCHAR(20),
    content             VARCHAR(20000) NOT NULL,
    recorder_member_id  BIGINT         NOT NULL,
    created_at          TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT pk_consultation PRIMARY KEY (consultation_id),
    CONSTRAINT fk_consultation_case FOREIGN KEY (case_id) REFERENCES case_record (case_id) ON DELETE CASCADE,
    CONSTRAINT fk_consultation_recorder FOREIGN KEY (recorder_member_id) REFERENCES member (member_id),
    CONSTRAINT ck_consultation_category CHECK (category IN ('초기상담', '중기상담', '종료상담', '정기상담', '긴급상담', '기타')),
    -- '기타'일 때만 기타 분류 내용을 넣는다
    CONSTRAINT ck_consultation_category_etc CHECK (
        (category = '기타' AND category_etc IS NOT NULL)
        OR (category <> '기타' AND category_etc IS NULL)
    )
);

-- 사례자 상세의 상담 목록(최신순), 최근 기록일 계산에 사용
CREATE INDEX ix_consultation_case_consulted ON consultation (case_id, consulted_at DESC);


-- 지역 선택 목록 (dim_region에서 만든다, 별도 시도·시군구 테이블 없음)
--   시도 이름은 시도 코드로 붙인다. 지역을 늘리면 CASE에 한 줄 추가한다.
CREATE VIEW v_sido AS
SELECT DISTINCT
    left(adm_cd10, 2) AS sido_code,
    CASE left(adm_cd10, 2)
        WHEN '11' THEN '서울특별시'
        WHEN '51' THEN '강원특별자치도'
    END AS sido_name
FROM dim_region;

CREATE VIEW v_sigungu AS
SELECT DISTINCT left(adm_cd10, 5) AS sigungu_code, left(adm_cd10, 2) AS sido_code, sgg_nm AS sigungu_name
FROM dim_region;


-- 사례자 목록·상세 조회용 (나이·연령대·최근 기록일 계산)
--   연령대(만 나이): 18세 이하 청소년, 19~39세 청년, 40~64세 중장년, 65세 이상 노년
CREATE VIEW v_case_summary AS
SELECT
    c.case_id,
    c.org_id,
    c.management_no,
    c.name,
    c.birth_date,
    a.age,
    CASE
        WHEN a.age <= 18 THEN '청소년'
        WHEN a.age <= 39 THEN '청년'
        WHEN a.age <= 64 THEN '중장년'
        ELSE '노년'
    END AS age_group,
    c.gender,
    left(c.dong_code, 2) AS sido_code,
    sd.sido_name,
    left(c.dong_code, 5) AS sigungu_code,
    r.sgg_nm AS sigungu_name,
    c.dong_code,
    r.adm_nm AS dong_name,
    c.first_registered_at,
    (SELECT max(s.consulted_at) FROM consultation s WHERE s.case_id = c.case_id) AS last_recorded_at
FROM case_record c
JOIN dim_region r ON r.adm_cd10 = c.dong_code
LEFT JOIN v_sido sd ON sd.sido_code = left(c.dong_code, 2)
CROSS JOIN LATERAL (SELECT date_part('year', age(current_date, c.birth_date))::int AS age) a;


-- 관리번호 발급: 기관별·최초 등록일 연도별 순번 (예: 2026-0001)
--   * 같은 트랜잭션에서 case_record INSERT까지 마쳐야 한다 (기관 행 잠금으로 동시 발급을 막는다).
--   * 가장 마지막 번호의 사례자를 지우면 그 번호가 다시 발급될 수 있다.
CREATE FUNCTION next_management_no(p_org_id BIGINT, p_first_registered_at DATE)
RETURNS VARCHAR(9)
LANGUAGE plpgsql
AS $$
DECLARE
    v_year TEXT := to_char(p_first_registered_at, 'YYYY');
    v_last VARCHAR(9);
BEGIN
    PERFORM 1 FROM organization WHERE org_id = p_org_id FOR UPDATE;

    SELECT max(management_no) INTO v_last
    FROM case_record
    WHERE org_id = p_org_id AND management_no LIKE v_year || '-%';

    RETURN v_year || '-' || lpad((coalesce(split_part(v_last, '-', 2)::INT, 0) + 1)::TEXT, 4, '0');
END;
$$;


