function orgOf(memberId: number): number {
  const member = seedMembers.find((item) => item.memberId === memberId)
  if (!member) throw new Error(`복지자원 담당자 예시가 없습니다: ${memberId}`)
  return member.orgId
}

/** 예시 등록일: 운영 시작 월의 1일 (운영 시작일이 이 날 뒤면 이 날) */
const LATEST_CREATED_AT = "2026-10-20"

export const seedResources: WelfareResource[] = SEEDS.map(({ createdAt, deletedAt, ...seed }, index) => {
  const monthStart = `${seed.periodStart.slice(0, 7)}-01`
  return {
    ...seed,
    resourceId: index + 1,
    orgId: orgOf(seed.managerMemberId),
    createdAt: createdAt ?? (monthStart < LATEST_CREATED_AT ? monthStart : LATEST_CREATED_AT),
    deletedAt: deletedAt ?? null,
  }
})
